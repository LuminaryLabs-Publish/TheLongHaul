import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const read=async path=>readFile(new URL(`../${path}`,import.meta.url),'utf8');
const bootstrap=await read('src/app/bootstrap.mjs');
const tileRenderer=await read('src/game/environment-tile-renderer.mjs');
const host=await read('src/app/prebuilt-tree-host.js');
const loader=await read('src/game/prebuilt-tree-library.mjs');
assert.match(bootstrap,/from ['"]\.\.\/game\/prebuilt-tree-library\.mjs['"]/);
assert.match(bootstrap,/Object\.assign\(globalThis,\s*\{\s*PREBUILT_TREE_VERSION/);
assert.match(bootstrap,/prebuilt-tree-host\.js/);
assert.match(bootstrap,/LongHaulPrebuiltTrees\?\.readyPromise/);
assert.ok(bootstrap.indexOf('environment-tiles-host.js')<bootstrap.indexOf('prebuilt-tree-host.js'));
assert.ok(bootstrap.indexOf('prebuilt-tree-host.js')<bootstrap.indexOf('menu-attract-host.js'));
assert.match(tileRenderer,/globalThis\.LongHaulPrebuiltTrees\?\.ready/);
assert.match(tileRenderer,/obj\.role\s*!==\s*['"]on-road-paint['"]/);
assert.match(tileRenderer,/\['tree','maple','oak','pine','fir','juniper','willow'\]/);
assert.match(host,/const beforeDecorate=decorateCell/);
assert.match(host,/const beforeRelease=releaseCell/);
assert.match(host,/const beforeClear=clearWorld/);
assert.match(host,/const beforeCloud=updateCloudLayers/);
assert.match(host,/removeProceduralTreeMeshes\(entry\)/);
assert.match(host,/new THREE\.InstancedMesh/);
assert.match(loader,/alphaTest:m\.alphaMode==='MASK'/);
assert.doesNotMatch(host,/coreWorld\.getWorld\(/);
assert.doesNotMatch(host,/setCargo|freight\.settle|payment|engine\.tick\(/);
console.log('PASS: V2 tree host loads after environment renderer, gates procedural foliage, exposes fallback and respects World and gameplay ownership.');