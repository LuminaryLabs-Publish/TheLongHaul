import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createEndlessHighway,endlessHighwayPoint} from '../src/game/endless-highway.mjs';
import {createPlayableRoadV3Course,playableRoadV3Point} from '../src/game/road-v3-playable-course.mjs';
import {ROAD_V3_VERSION} from '../src/game/road-v3-geometry.mjs';
import {nearestRoad,terrainHeight,roadV3GroundContact} from '../src/game/world-base.mjs';
import {attachFreightTerminalStart,terminalLocalPoint,terminalWorldPoint,terminalObstacleVolumes,freightTerminalGroundHeight,FREIGHT_TERMINAL_MERGE_PROGRESS,FREIGHT_TERMINAL_VERSION} from '../src/game/freight-terminal-start.mjs';
import {parseFreightTerminalGlb} from '../src/game/freight-terminal-glb.mjs';
const file=new URL('../assets/freight-terminal/terminal-yard.glb',import.meta.url);
const data=readFileSync(file);const buf=data.buffer.slice(data.byteOffset,data.byteOffset+data.byteLength);
const parsed=parseFreightTerminalGlb(buf);
assert.ok(parsed.meshes.length>20&&parsed.triangles>30000,'real GLB batches decoded');
assert.ok(parsed.materials.some(m=>m.name==='yard_asphalt'),'yard pavement preserved');
assert.ok(parsed.materials.some(m=>m.name==='asphalt'),'original GLB retains source road for offline review; runtime excludes it');
let checks=0;
for(const version of ['v2','v3'])for(let n=0;n<3;n++){
 const seed=`terminal-seed-${n}`;
 const graph=version==='v3'?createPlayableRoadV3Course(seed):createEndlessHighway(seed);
 const source={...graph.origin};
 attachFreightTerminalStart(graph);
 assert.equal(graph.freightTerminal.id,FREIGHT_TERMINAL_VERSION);
 assert.ok(graph.origin.id==='terminal:spawn');
 assert.equal(graph.edges.filter(e=>e.id==='terminal:start-ramp').length,1);
 assert.ok(graph.origin.x!==source.x||graph.origin.z!==source.z,'fresh spawn moved into yard');
 const start=graph.edges.find(e=>e.id==='terminal:start-ramp');
 assert.equal(start.samples.length>100,true);
 const merge=version==='v3'?playableRoadV3Point(graph,FREIGHT_TERMINAL_MERGE_PROGRESS):endlessHighwayPoint(graph,FREIGHT_TERMINAL_MERGE_PROGRESS);
 const last=start.samples.at(-1);
 assert.ok(Math.hypot(last.x-merge.x,last.z-merge.z)<.001,'ramp actually connects to highway');
 assert.ok(Math.abs(last.y-merge.y)<.001,'ramp matches highway deck elevation');
 assert.ok(start.samples.every(p=>[p.x,p.y,p.z,p.heading,p.nx,p.nz,p.progress].every(Number.isFinite)));
 assert.ok(start.samples.every((p,i)=>i===0||p.progress>=start.samples[i-1].progress),'progress monotonic');
 assert.ok(start.samples.every(p=>Math.abs(p.grade)<.15),'no violent ramp grade transitions');
 const yardGround=terrainHeight(graph,graph.origin.x,graph.origin.z);
 assert.ok(Math.abs(yardGround-graph.freightTerminal.y)<.5,'yard ground anchored to real surface');
 const near=nearestRoad(graph,{...graph.origin,y:graph.origin.y+.9});
 assert.equal(near.edge.id,'terminal:start-ramp','player starts on a driveable start edge');
 assert.ok(near.distance<.05);
 if(version==='v3'){
   const deck=roadV3GroundContact(graph,{x:graph.origin.x,y:graph.origin.y+.9,z:graph.origin.z});
   assert.ok(deck&&Math.abs(deck.height-graph.origin.y)<.2,'spawn road deck matches physical contact');
 }
 const site=graph.freightTerminal;
 const sample=terminalWorldPoint(site,[12,.2,-167]);
 const local=terminalLocalPoint(site,sample);
 assert.ok(Math.hypot(local.x-12,local.z+167)<1e-6,'asset transform reversible');
 const collisions=terminalObstacleVolumes(site);
 assert.equal(collisions.length,40);
 assert.ok(collisions.every(o=>Number.isFinite(o.x+o.y+o.z)&&o.height>0&&o.radius>0));
 const clear=collisions.every(o=>Math.hypot(o.x-graph.origin.x,o.z-graph.origin.z)>o.radius+4);
 assert.ok(clear,'live player can spawn without overlapping warehouse/trucks');
 const oldLen=graph.edges.length;attachFreightTerminalStart(graph);
 assert.equal(graph.edges.length,oldLen,'reattachment does not duplicate ramp');
 const roadStart=graph.edges.find(e=>e.id==='terminal:start-ramp').samples[0];
 assert.ok(Math.abs(roadStart.y-graph.origin.y)<.001);
 checks++;
}
const historical=createEndlessHighway('historic-save');
assert.equal(historical.freightTerminal,undefined,'old course unchanged when the hub is not attached');
assert.equal(freightTerminalGroundHeight(historical,0,0,8),8,'old terrain unchanged');
console.log(JSON.stringify({status:'PASS',seeds:3,versions:2,scenarios:checks,glbBatches:parsed.meshes.length,glbTriangles:parsed.triangles,collisionProxies:40}));
